package id.my.tudemaha.lobos.di

import org.koin.core.context.startKoin
import org.koin.dsl.KoinAppDeclaration

fun initKoin(appDeclaration: KoinAppDeclaration = {}) =
    startKoin {
        appDeclaration()
        modules(
            platformModule,
            networkModule,
            repositoryModule,
            viewModelModule
        )
    }